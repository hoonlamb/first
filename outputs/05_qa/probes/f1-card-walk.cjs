const { launch, makeCard, BASE, SHOTS } = require('./lib.cjs')
const out = {}
;(async () => {
  const { browser, page, errors } = await launch()
  // A. guard
  await page.goto(BASE + '#/app/walk')
  await page.waitForTimeout(300)
  out.guardUrl = page.url(); out.guardNotice = await page.locator('.notice').textContent().catch(() => null)
  await page.screenshot({ path: SHOTS + 'f-app-empty-390.png' })
  // B. builder validation
  await page.goto(BASE + '#/app/card/new')
  await page.getByRole('button', { name: '다음' }).click()
  out.emptyNameErr = await page.locator('.error').textContent()
  await page.getByLabel('이름').fill('가나다라마바사아자차카타파하')
  out.longNameValue = await page.getByLabel('이름').inputValue()
  await page.getByRole('button', { name: '다음' }).click()
  out.longNameErr = await page.locator('.error').textContent().catch(() => null)
  await page.getByLabel('이름').fill('')
  await page.getByLabel('이름').type('🐶🐶🐶🐶🐶🐶🐶')
  out.emojiValue = await page.getByLabel('이름').inputValue()
  out.emojiCharCount = [...out.emojiValue].length
  await page.getByRole('button', { name: '다음' }).click()
  out.emojiErr = await page.locator('.error').textContent().catch(() => null)
  await page.screenshot({ path: SHOTS + 'f-builder-emoji-name.png' })
  // leaving via header 설정 link while dirty
  await page.getByRole('link', { name: '설정' }).click()
  await page.waitForTimeout(300)
  out.dirtyLeaveViaHeader = { url: page.url(), dialogOpen: await page.locator('dialog[open]').count() }
  // browser back from builder (dirty)
  await page.goto(BASE + '#/app')
  await page.goto(BASE + '#/app/card/new')
  await page.getByLabel('이름').fill('보름')
  await page.goBack(); await page.waitForTimeout(300)
  out.dirtyLeaveViaBack = { url: page.url(), dialogOpen: await page.locator('dialog[open]').count() }
  // C. batchim name -> particle check
  await makeCard(page, { name: '보름', comfort: 8, triggers: ['작은 개'] })
  out.homeText = (await page.locator('main').innerText()).slice(0, 300)
  await page.goto(BASE + '#/app/card/edit')
  await page.getByRole('button', { name: '다음' }).click()
  out.batchimTitle = await page.locator('h1').innerText()
  await page.screenshot({ path: SHOTS + 'f-batchim-particle.png' })
  // slider rapid changes
  const r = page.getByLabel('편한 거리(미터)')
  await r.focus()
  const t0 = Date.now()
  for (let k = 0; k < 40; k++) await page.keyboard.press(k % 2 ? 'ArrowRight' : 'ArrowUp')
  out.rapidSliderValue = await r.inputValue(); out.rapidMs = Date.now() - t0
  out.comfortLive = await page.locator('.comfort__value').innerText()
  // cancel edit via 취소 -> confirm
  await page.getByRole('button', { name: '취소' }).click()
  out.editCancelDialog = await page.locator('dialog[open] h2').innerText().catch(() => null)
  await page.keyboard.press('Escape'); await page.waitForTimeout(200)
  out.afterEscFocus = await page.evaluate(() => document.activeElement && (document.activeElement.textContent || document.activeElement.tagName))
  await page.getByRole('button', { name: '취소' }).click()
  await page.locator('dialog[open]').getByRole('button', { name: '나가기' }).click()
  // show mode
  await page.getByRole('link', { name: /보여주기/ }).click()
  await page.waitForTimeout(600)
  out.showText = await page.locator('.showmode').innerText()
  await page.screenshot({ path: SHOTS + 'f-show-390.png' })
  await page.keyboard.press('Escape'); await page.waitForTimeout(200)
  out.afterShowEscUrl = page.url()
  out.focusAfterShowClose = await page.evaluate(() => document.activeElement && document.activeElement.outerHTML.slice(0, 80))
  // D. walk
  await page.goto(BASE + '#/app/walk')
  await page.getByRole('button', { name: '산책 시작' }).dblclick()
  await page.waitForTimeout(200)
  out.walksAfterDbl = await page.evaluate(() => JSON.parse(localStorage.getItem('dangq.demo.v1')).activeWalk && 'active')
  await page.getByRole('button', { name: '마주침 기록' }).click()
  await page.getByRole('button', { name: '기록하기' }).click()
  out.encErr = await page.locator('dialog[open] .error').innerText()
  await page.locator('dialog[open]').getByRole('radio', { name: '3m', exact: true }).check()
  await page.locator('dialog[open]').getByRole('radio', { name: '편안했어요' }).check()
  await page.locator('dialog[open]').getByRole('button', { name: '기록하기' }).click()
  await page.waitForTimeout(300)
  out.encCountAfterDbl = await page.evaluate(() => JSON.parse(localStorage.getItem('dangq.demo.v1')).activeWalk.encounters.length)
  await page.getByRole('button', { name: '마주침 기록' }).click()
  await page.locator('dialog[open]').getByRole('radio', { name: '5m', exact: true }).check()
  await page.locator('dialog[open]').getByRole('radio', { name: '반응했어요' }).check()
  await page.locator('dialog[open]').getByRole('button', { name: '기록하기' }).click()
  await page.screenshot({ path: SHOTS + 'f-walk-active.png' })
  // reload mid-walk
  await page.reload(); await page.waitForTimeout(500)
  out.afterReloadWalk = await page.locator('.pagehead').innerText()
  // back mid-walk and return
  await page.goBack(); await page.waitForTimeout(300); await page.goForward(); await page.waitForTimeout(300)
  await page.getByRole('button', { name: '산책 끝내기' }).click()
  await page.waitForTimeout(300)
  out.summary1 = await page.locator('main').innerText()
  await page.screenshot({ path: SHOTS + 'f-walk-summary-suggest.png', fullPage: true })
  const sBtn = page.getByRole('button', { name: /카드를 \d+m로 바꾸기/ })
  out.suggestBtn1 = await sBtn.innerText()
  await sBtn.click(); await page.waitForTimeout(300)
  out.summary2 = await page.locator('main').innerText()
  await page.screenshot({ path: SHOTS + 'f-walk-summary-flipflop.png', fullPage: true })
  out.cardComfortNow = await page.evaluate(() => JSON.parse(localStorage.getItem('dangq.demo.v1')).card.comfort)
  const sBtn2 = page.getByRole('button', { name: /카드를 \d+m로 바꾸기/ })
  if (await sBtn2.count()) { out.suggestBtn2 = await sBtn2.innerText() }
  out.errors = errors
  console.log(JSON.stringify(out, null, 1))
  await browser.close()
})().catch((e) => { console.log(JSON.stringify(out, null, 1)); console.error(e); process.exit(1) })
